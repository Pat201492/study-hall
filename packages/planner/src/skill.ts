import { PLAN_ROLE } from './planRole.js';
import { loadRubric, type RubricText } from './rubric.js';

// The /plan-feature skill for a plain terminal, authored ONCE from the same
// PLAN_ROLE the dashboard session uses. Rendered at install time so the rubric
// text is baked in (the skill runs in whatever repo the user is in; the rubric
// lives in study-hall) and stamped with the rubric's sha so drift is visible.

export interface SkillOptions {
  /** The dashboard's MCP endpoint for a repo, e.g. http://127.0.0.1:4800/mcp/owner/name */
  mcpUrl: string;
  token: string;
  rubric?: RubricText;
}

const TOOLS_BLOCK = [
  '## Tools',
  '',
  'The `plan` MCP server (registered by the installer) exposes the planner tools:',
  '`list_repo_context`, `lint_issue`, `find_duplicate_issue`, `propose_issues` and',
  '`file_issues` (which requires `confirm: true` — never pass it unless the user',
  'explicitly said to file). If the tools are NOT available in this session, do not',
  'improvise: put every draft inside a fenced ```planner-proposals``` block as a JSON',
  'array of `{ key, title, difficulty, dependsOn, owns, body }` objects and tell the',
  'user to paste it into the study-hall Planner tab, which lints and stages it.',
  '',
].join('\n');

export function renderClaudeSkill(o: SkillOptions): string {
  const r = o.rubric ?? loadRubric();
  return [
    '---',
    'name: plan-feature',
    'description: Turn a feature idea into rubric-compliant GitHub issues that autonomous students can build first try. Drafts, lints and stages; the orchestrator files.',
    'argument-hint: <feature idea>',
    '---',
    '',
    `<!-- generated by study-hall from PLAN_ROLE + ISSUE-RUBRIC.md (sha256 ${r.sha256.slice(0, 12)}); do not edit by hand -->`,
    '',
    'The feature idea to plan: $ARGUMENTS',
    '',
    PLAN_ROLE,
    '',
    TOOLS_BLOCK,
    '## Issue rubric (verbatim)',
    '',
    r.text.trim(),
    '',
  ].join('\n');
}

export function renderCodexSkill(o: SkillOptions): string {
  const r = o.rubric ?? loadRubric();
  return [
    '# plan-feature',
    '',
    `<!-- generated by study-hall from PLAN_ROLE + ISSUE-RUBRIC.md (sha256 ${r.sha256.slice(0, 12)}); do not edit by hand -->`,
    '',
    'Use this prompt to plan a feature with the study-hall planner tools from a Codex session.',
    'Start Codex with the `plan` MCP server configured (see `~/.codex/config.toml` below), then paste',
    'this file\'s body as the first message followed by the feature idea.',
    '',
    '```toml',
    '[mcp_servers.plan]',
    `url = "${o.mcpUrl}"`,
    `http_headers = { "X-Plan-Token" = "${o.token}" }`,
    'startup_timeout_sec = 30',
    'tool_timeout_sec = 120',
    '```',
    '',
    '---',
    '',
    PLAN_ROLE,
    '',
    TOOLS_BLOCK,
    '## Issue rubric (verbatim)',
    '',
    r.text.trim(),
    '',
  ].join('\n');
}

/** The one-liner that registers the dashboard's MCP server for a plain `claude` terminal. */
export function claudeMcpAddCommand(o: SkillOptions): string {
  return `claude mcp add --transport http --scope user plan "${o.mcpUrl}" --header "X-Plan-Token: ${o.token}"`;
}
